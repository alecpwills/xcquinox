"""Hygiene of the tracked tree: no training snapshot is tracked, no tracked file is large
enough to be a result blob, the data directories and the results directory hold exactly what
their lists name, no test-named module sits outside a tests directory, and every architecture
diagram is a source with its render beside it.

The index tests read ``git ls-files``, so a staged addition is seen before its commit; the rule
tests exercise each predicate on names that must fire it and names that must not. The size cap
is 16 MiB: the largest file the tree keeps is the results summary PDF (12.4 MB). A document that
grows past the cap is a decision to take here, not an accident to let through. Sizes are read
from the working tree, so the size test runs on a full checkout. What the tests do not catch is
a result tree added under a new directory name with every file under the cap and no numbered
snapshot: the cap bounds each file such a tree can carry.
"""
from __future__ import annotations

import os
import re
import subprocess
import tomllib
from pathlib import Path
from typing import Iterable

import pytest

_ROOT = Path(__file__).resolve().parents[1]

#: the periodic ``<name>.eqx.<step>`` snapshots a training run writes
_NUMBERED_SNAPSHOT = re.compile(r"\.eqx\.\d+$")

SIZE_CAP_BYTES = 16 * 1024 * 1024

#: the v7 reports directory: the summary, the deck with its frames and code appendix, the
#: excerpts and the five figure sets the documents cite, and nothing else
REPORTS_V7 = "reports/v7/"
REPORTS_V7_CONTENTS = (
    "SUMMARY_v7_2026-09-15.md",
    "SUMMARY_v7_2026-09-15.tex",
    "SUMMARY_v7_2026-09-15.pdf",
    "SLIDES_v7_2026-09-15.tex",
    "SLIDES_v7_2026-09-15.pdf",
    "SLIDES_v7_2026-09-15_frames.tex",
    "SLIDES_v7_2026-09-15_code_appendix.tex",
    "slides_code/",
    "figures_dfs_step7_v7_family/",
    "figures_dfs_step7_v7_family_pretrain/",
    "figures_dfs_step7_v7_family_val_best/",
    "figures_dfs_step7_v7_family_val_best_excl_tail/",
    "figures_dfs_step7_v7_subsets/",
)

#: the architecture diagrams: every tracked ``.dot`` has its ``.svg`` render beside it and
#: nothing else
DIAGRAMS_ROOT = "docs/architecture/diagrams/"
_GRAPHVIZ_VERSION = re.compile(rb"Generated by graphviz version (\S+)")
_SVG_LABEL = re.compile(rb"<(title|text)\b[^>]*>([^<]*)</\1>")

