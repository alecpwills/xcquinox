"""Generate gga_training_example-step7.ipynb.

Pattern matches notebooks/_build_step{4,5,6}_notebook.py: assemble cells
into nbformat structure, write .ipynb, optionally execute end-to-end.

Step-7 plan (mixed-pool refactor 2026-05-07):
  - Build the Dick 2021 SI II training pool as 26 mixed TrainingPoints
    (21 AE + 3 BH76 + 2 IP13) via xcquinox.alec.training_points.
  - Extract (rho^{1/3}, s, alpha) PER SPECIES (deduped across points),
    then concatenate across each point's species (design choice "a")
    to form one descriptor block per training point.
  - Build reference 3-histogram from the per-point descriptors so a
    multi-species point (BH76 reaction) carries proportionally larger
    weight in the reference distribution.
  - Sweep r in {1,2,3,4,5,6,7,12,15,18} x {l2, jsd} x {oneshot, full_3}
    = 40 training runs.  Atom regularizers restricted to Dick H/Li.
    No HBPT augmentation (dropped 2026-05-07).
  - Post-process: 6+1 figures + headline.json

Citations:
  - PBE 1996  (PRL 77, 3865) -- descriptor s
  - SCAN 2015 (PRL 115, 036402) -- descriptor alpha
  - Lin 1991  (IEEE TIT 37, 145) -- JSD
  - Chen 2018 (arXiv:1711.02257) -- GradNorm
  - Dick 2021 (PRB 104, L161109) -- candidate pool
"""
