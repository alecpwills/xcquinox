        "for p in points:\n"
        "    _by_kind[p.kind] += 1\n"
        "print(f'Mixed pool: {len(points)} points '\n"
        "      f'({_by_kind[\"ae\"]} AE + {_by_kind[\"bh76\"]} BH76 + '\n"
