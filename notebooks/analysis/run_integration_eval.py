"""Generate the step-6 integration-pretrain analysis report + comparison plots.

Identical to ``run_unweighted_eval.py`` except for the run directory and
label. ``comparison_lib`` is run-agnostic; once the integration-origin
sweep finishes, executing this script produces the same five figures
and a structured report under ``reports_local/step6_integration_analysis/``.

A subsequent comparison report (unweighted vs integration side-by-side)
can be generated by reading both runs' ``headline_stats.json`` files;
that helper will be added when both sweeps are complete.
"""
from __future__ import annotations

from pathlib import Path
import json
import sys

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

from comparison_lib import (  # noqa: E402
    load_run_artifacts,
    headline_stats,
    plot_baseline_reduction,
    plot_density_vs_energy_tradeoff,
    plot_in_dist_vs_transfer,
    plot_loss_strategy_heatmap,
    plot_arch_comparison,
)


REPO = HERE.parent.parent
RUN_DIR = REPO / "notebooks" / "checkpoints_step6" / "integration"
RUN_LABEL = "integration"
OUT_DIR = REPO / "reports_local" / "step6_integration_analysis"
FIG_DIR = OUT_DIR / "figures"


def main() -> int:
    if not RUN_DIR.is_dir():
        print(f"NOTE: {RUN_DIR} does not exist yet — integration sweep not finished.")
        print("      Re-run this script once the integration-pretrain training cell completes.")
        return 0

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    FIG_DIR.mkdir(parents=True, exist_ok=True)

    print(f"Loading artifacts from {RUN_DIR} ...")
    art = load_run_artifacts(RUN_DIR)
    for k, v in art.items():
        print(f"  {k}: {None if v is None else v.shape}")

    print(f"\nGenerating figures into {FIG_DIR} ...")
    plot_baseline_reduction(art,           FIG_DIR / "fig1_baseline_reduction.png",         RUN_LABEL)
    plot_density_vs_energy_tradeoff(art,   FIG_DIR / "fig2_density_vs_energy_tradeoff.png", RUN_LABEL)
    plot_in_dist_vs_transfer(art,          FIG_DIR / "fig3_in_dist_vs_transfer.png",        RUN_LABEL)
    plot_loss_strategy_heatmap(art,        FIG_DIR / "fig4_loss_strategy_heatmap.png",      RUN_LABEL)
    plot_arch_comparison(art,              FIG_DIR / "fig5_arch_comparison.png",            RUN_LABEL)

    stats = headline_stats(art)
    (OUT_DIR / "headline_stats.json").write_text(json.dumps(stats, indent=2))
    print("\nHeadline stats:")
    print(json.dumps(stats, indent=2))

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
